"""Generate src/NeonLegacyGroups.inc from NEON_LUA.txt.

Reads run_grid_balance_variables() and records, for every grid_logic_var / power_company_buildings
assignment that sums sc4game.automata.get_source_building_count(...), the list of occupant groups and
whether the sum is a COUNT, a kVA RATING (x kva_rating) or a MWh POWER (x mwh_rating).
"""
import re, sys
src = open(sys.argv[1], encoding='latin-1').read().splitlines()
start = next(i for i, l in enumerate(src) if l.startswith('function run_grid_balance_variables'))
end = next(i for i in range(start, len(src)) if src[i].startswith('function voltage_variance'))
rows = []
for line in src[start:end]:
    m = re.match(r'\s*(grid_logic_var|power_company_buildings)\.([A-Z0-9_]+)\s*=\s*(.*)$', line)
    if not m or 'get_source_building_count' not in m.group(3):
        continue
    table, name, expr = m.groups()
    ogs = [int(h, 16) for h in re.findall(r'get_source_building_count\(hex2dec\("([0-9A-Fa-f]{8})"\)\)', expr)]
    if 'kva_rating' in expr: kind = 'Rating'
    elif 'mwh_rating' in expr: kind = 'Power'
    elif 'power_storage_stacks' in expr: kind = 'Stacks'
    else: kind = 'Count'
    # PV panel sets are added through PV_GENERATORS / PV_S_SOLAR_UNITS, handled in C++.
    rest = re.sub(r'sc4game\.automata\.get_source_building_count\(hex2dec\("[0-9A-Fa-f]{8}"\)\)(\*[a-z_]+\.ID_[0-9A-Fa-f]{8}(_A)?)?', '', expr)
    extras = re.findall(r'grid_logic_var\.([A-Z_0-9]+)', rest)
    assert len(extras) <= 1, (name, extras)
    extra = extras[0] if extras else ''
    rows.append((table, name, kind, ogs, extra))
# Groups NEON uses that the original Lua does not have (DLL only).
#   0xBB350079  Large Fission #2: BD VVER-1000 Pressurized Reactor (has its own query UI BB353079)
NEON_ONLY_GROUPS = {'LARGE_FISSION_COUNT': [0xBB350079], 'LARGE_FISION_RATING': [0xBB350079], 'L_FISSION_POWER': [0xBB350079]}
rows = [(t, n, k, ogs + NEON_ONLY_GROUPS.get(n, []), e) for t, n, k, ogs, e in rows]
out = ['// Generated by tools/gen_legacy_groups.py from NEON_LUA.txt - do not edit by hand.',
       '// { Lua table, "lua variable", kind, "extra grid_logic_var term or empty", { occupant groups... } }']
for table, name, kind, ogs, extra in rows:
    out.append('NEON_LEGACY_SUM(NeonTable::%s, "%s", NeonSumKind::%s, "%s", {%s})' % (
        'Company' if table == 'power_company_buildings' else 'Grid', name, kind, extra, ', '.join('0x%08X' % o for o in ogs)))
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(rows), 'sums;', sum(len(r[3]) for r in rows), 'group references')


# Numeric per-group tables used as a fallback when an exemplar carries no rating property.
def table(name):
    i = next(k for k, l in enumerate(src) if re.match(r'^%s\s*=\s*\{' % name, l))
    vals = {}
    for l in src[i + 1:]:
        if l.startswith('}'): break
        m = re.match(r'\s*ID_([0-9A-Fa-f]{8})(_A)?\s*=\s*([0-9.]+)\s*,?', l)
        if m and not m.group(2):
            vals.setdefault(int(m.group(1), 16), float(m.group(3)))
        elif m and m.group(2) and name == 'mwh_rating':
            # Waste-to-energy: ID_xxx is the live value (0 in the table), ID_xxx_A the plant's maximum output.
            vals[int(m.group(1), 16)] = float(m.group(3))
    return vals
lines = ['// Generated by tools/gen_legacy_groups.py - fallback values from the Lua tables.',
         '// { occupant group, kVA, MWh, storage stacks }']
kva, mwh, stk = table('kva_rating'), table('mwh_rating'), table('power_storage_stacks')
for og in sorted(set(kva) | set(mwh) | set(stk)):
    lines.append('NEON_LEGACY_VALUE(0x%08X, %g, %g, %g)' % (og, kva.get(og, 0), mwh.get(og, 0), stk.get(og, 0)))
open(sys.argv[2].replace('Groups', 'Values'), 'w').write('\n'.join(lines) + '\n')
print(len(lines) - 2, 'fallback rows', len(kva), len(mwh), len(stk))
